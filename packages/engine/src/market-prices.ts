/**
 * Département depuis un CP — Corse (2A/2B) et DROM (971–976) inclus.
 */
export function deptFromPostal(postalCode: string): string {
  if (!postalCode || postalCode.length < 2) return "default";
  const cp = postalCode.replace(/\D/g, "");
  if (cp.length < 2) return "default";
  // Corse
  if (cp.startsWith("200") || cp.startsWith("201")) return "2A";
  if (cp.startsWith("202") || cp.startsWith("206")) return "2B";
  // DROM (3 chiffres)
  if (/^97[1-6]/.test(cp)) return cp.slice(0, 3);
  return cp.slice(0, 2);
}

export function pricePerSqmForDept(dept: string): number {
  return PRICE_PER_SQM_BY_DEPT[dept] ?? PRICE_PER_SQM_BY_DEPT.default;
}

export function pricePerSqmForPostal(postalCode: string): number {
  return pricePerSqmForDept(deptFromPostal(postalCode));
}

/** CP d'échantillon pour interroger la DVF au niveau département. */
export function samplePostalsForDept(dept: string, preferredPostal?: string): string[] {
  const out: string[] = [];
  if (preferredPostal) {
    const pref = preferredPostal.replace(/\D/g, "").slice(0, 5);
    if (pref.length === 5) out.push(pref);
  }
  const known = DEPT_SAMPLE_POSTALS[dept] ?? [];
  for (const p of known) {
    if (!out.includes(p)) out.push(p);
  }
  if (dept.length === 2 && !out.some((p) => p.startsWith(dept))) {
    out.push(`${dept}000`);
  }
  return out.slice(0, 5);
}
